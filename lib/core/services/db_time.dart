/// DB에 시각·날짜를 넣을 때 쓰는 변환.
///
/// ## 왜 한 곳에 모았나
///
/// 앱 전체가 9시간 어긋난 적이 있습니다. 로컬 시각을 그대로
/// `toIso8601String()`으로 보냈기 때문입니다.
///
/// `DateTime(2026, 8, 12, 3, 17).toIso8601String()`은
/// `"2026-08-12T03:17:00.000"` 입니다 — **`Z`도 `+09:00`도 붙지 않습니다.**
/// PostgreSQL은 `timestamptz` 컬럼에 오프셋 없는 문자열이 들어오면 세션
/// 시간대(Supabase 기본값 UTC)로 해석합니다. 그래서 새벽 3시 17분이
/// **UTC 3시 17분**으로 저장됩니다.
///
/// 읽을 때는 `DateTime.parse(...).toLocal()`을 하므로 UTC 3:17이 한국시간
/// 12:17이 됩니다. 저장할 때만 변환이 빠져 한쪽만 처리된 상태였습니다.
///
/// ## 시각과 날짜를 구분하는 이유
///
/// 날짜 컬럼(`date`)에 [toDbTime]을 쓰면 **날짜가 하루 밀립니다.**
/// 오전 9시 이전의 한국 시각은 UTC로 바꾸면 전날이 되기 때문입니다.
/// 생년월일이 하루 당겨지면 개월 수가 바뀌고, 개월 수는 체온 판정의
/// 경계입니다.
library;

/// `timestamptz` 컬럼에 넣을 문자열.
///
/// 반드시 UTC로 바꿔 오프셋을 붙입니다. 언제 일어난 일인지가 시간대와
/// 무관하게 하나로 정해집니다.
String toDbTime(DateTime at) => at.toUtc().toIso8601String();

/// `date` 컬럼에 넣을 문자열(`YYYY-MM-DD`).
///
/// **UTC로 바꾸지 않습니다.** 생년월일이나 측정일은 "그 사람이 사는 곳의
/// 달력 날짜"이지 특정 순간이 아닙니다. UTC로 옮기면 오전 9시 이전에
/// 기록한 날짜가 전날로 밀립니다.
String toDbDate(DateTime at) =>
    '${at.year.toString().padLeft(4, '0')}-'
    '${at.month.toString().padLeft(2, '0')}-'
    '${at.day.toString().padLeft(2, '0')}';
