import 'package:flutter/foundation.dart';

/// "지금 다시 읽으세요"라는 신호.
///
/// 하단 탭은 [IndexedStack]으로 만들어져 있어 **화면이 살아 있는 채로**
/// 숨겨집니다. 그래서 `initState`가 한 번만 돌고, 탭을 오가도 다시 읽지
/// 않습니다. 홈에서 체온을 적고 기록 탭으로 가면 "아직 남긴 기록이
/// 없습니다"가 그대로 있었습니다 — 그 문구가 시키는 대로 했는데도요.
///
/// 앱을 백그라운드에 두었다 돌아오는 경우도 같습니다. 홈의 '오늘의 기록'은
/// 자정을 넘겨도 어제 값을 들고 있었습니다.
///
/// **탭마다 따로 둡니다.** 신호 하나를 모두가 듣게 하면 탭을 한 번 누를
/// 때마다 다섯 화면이 전부 다시 읽어 스무 번쯤 질의가 나갑니다. 보이는
/// 화면만 울립니다.
class RefreshSignal extends ChangeNotifier {
  void fire() => notifyListeners();
}
